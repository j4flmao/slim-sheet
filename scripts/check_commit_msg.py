"""commit-msg hook: enforce the org's Conventional Commits rule (.claude/rules/commit-standards.md).

    <type>(<scope>)!: <subject>
    - type: feat fix docs style refactor perf test chore build ci revert
    - subject: imperative, lowercase first letter, no trailing period, header <= 72 chars
      (the org rule asks for subjects under 50; longer ones only warn)

Merge, revert, fixup! and squash! messages generated by git are allowed as-is.
Usage (git passes the message file): python scripts/check_commit_msg.py .git/COMMIT_EDITMSG
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

TYPES = (
    "feat",
    "fix",
    "docs",
    "style",
    "refactor",
    "perf",
    "test",
    "chore",
    "build",
    "ci",
    "revert",
)
HEADER = re.compile(
    rf"^(?P<type>{'|'.join(TYPES)})(\((?P<scope>[a-z0-9._/-]+)\))?(?P<bang>!)?: (?P<subject>.+)$"
)
PASS_THROUGH = ("Merge ", "Revert ", "fixup! ", "squash! ", "amend! ")
MAX_HEADER = 72
SOFT_SUBJECT = 50


def check(message: str) -> list[str]:
    """Return problems with the commit message (empty list = valid)."""
    lines = [line for line in message.splitlines() if not line.startswith("#")]
    header = lines[0].strip() if lines else ""
    if header.startswith(PASS_THROUGH):
        return []
    match = HEADER.match(header)
    if not match:
        return [
            f"header must look like 'type(scope): subject' with type in: {', '.join(TYPES)}",
            f"got: {header!r}",
        ]
    subject = match.group("subject")
    problems = []
    if len(header) > MAX_HEADER:
        problems.append(f"header is {len(header)} characters (max {MAX_HEADER})")
    if subject[0].isupper():
        problems.append("subject must start with a lowercase letter")
    if subject.endswith("."):
        problems.append("subject must not end with a period")
    if len(lines) > 1 and lines[1].strip():
        problems.append("leave a blank line between the header and the body")
    return problems


def main(argv: list[str]) -> int:
    if len(argv) != 2:
        sys.stderr.write("usage: check_commit_msg.py <commit-message-file>\n")
        return 2
    message = Path(argv[1]).read_text(encoding="utf-8")
    problems = check(message)
    if problems:
        sys.stderr.write("commit message rejected (Conventional Commits):\n")
        sys.stderr.writelines(f"  - {p}\n" for p in problems)
        sys.stderr.write("example: feat(query): add offset paging\n")
        return 1
    subject = HEADER.match(message.splitlines()[0])
    if subject and len(subject.group("subject")) > SOFT_SUBJECT:
        sys.stderr.write(
            f"note: subject is over {SOFT_SUBJECT} characters; consider shortening it\n"
        )
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
